-- Synthetic 60-column test table for LLM chunking (PLAN.md Tue 10, Q4: "a 60-column test table proposes cleanly").
-- Generated from range(), deterministic, reads no product data (so no mask or row filter is baked in) and has no
-- region column (no row-filter join-up). Not part of setup: run by hand, e.g.
--   ./scripts/sql.sh -f sql/test/wide_60.sql
-- IF NOT EXISTS: a re-run never wipes the column comments and tags apply has set.
-- Names mix clear terms (fuzzy), abbreviations and vague names, so a good share reaches the LLM.
CREATE TABLE IF NOT EXISTS ${catalog}.${raw_schema}.wide_60 AS
SELECT
  concat('POL', lpad(CAST(id AS STRING), 7, '0')) AS policy_number,
  concat('CLM', lpad(CAST(id * 3 AS STRING), 7, '0')) AS claim_ref,
  concat('Q', lpad(CAST(id * 7 AS STRING), 8, '0')) AS quote_no,
  concat('C', lpad(CAST(id % 900 AS STRING), 6, '0')) AS cust_ref,
  concat('BRK', lpad(CAST(id % 40 AS STRING), 3, '0')) AS broker_cd,
  concat('UW', lpad(CAST(id % 25 AS STRING), 3, '0')) AS uw_code,
  date_add(DATE'2024-01-01', CAST(id % 700 AS INT)) AS inception_date,
  date_add(DATE'2025-01-01', CAST(id % 700 AS INT)) AS expiry_dt,
  date_add(DATE'2024-06-01', CAST(id % 500 AS INT)) AS loss_date,
  date_add(DATE'2024-06-15', CAST(id % 500 AS INT)) AS notified_on,
  round(500 + (hash(id, 1) % 5000 + 5000) * 0.37, 2) AS gross_premium,
  round(400 + (hash(id, 2) % 4000 + 4000) * 0.31, 2) AS net_prem,
  round((hash(id, 3) % 90000 + 90000) * 1.0, 2) AS sum_insured_amt,
  round((hash(id, 4) % 2500 + 2500) * 1.0, 2) AS excess,
  round((hash(id, 5) % 30 + 30) / 2.0, 2) AS commission_pct,
  round((hash(id, 6) % 20000 + 20000) * 1.0, 2) AS incurred,
  round((hash(id, 7) % 15000 + 15000) * 1.0, 2) AS reserve_amount,
  round((hash(id, 8) % 12000 + 12000) * 1.0, 2) AS paid_to_date,
  round((hash(id, 9) % 3000 + 3000) * 1.0, 2) AS recovery,
  element_at(array('GBP', 'USD', 'EUR'), CAST(id % 3 + 1 AS INT)) AS currency,
  element_at(array('motor', 'property', 'liability', 'marine'), CAST(id % 4 + 1 AS INT)) AS line_of_business,
  element_at(array('open', 'closed', 'reopened'), CAST(id % 3 + 1 AS INT)) AS clm_status,
  element_at(array('live', 'lapsed', 'cancelled'), CAST(id % 3 + 1 AS INT)) AS pol_stat,
  element_at(array('new', 'renewal'), CAST(id % 2 + 1 AS INT)) AS business_type,
  element_at(array('direct', 'broker', 'aggregator'), CAST(id % 3 + 1 AS INT)) AS channel,
  element_at(array('Y', 'N'), CAST(id % 2 + 1 AS INT)) AS litigation_flag,
  element_at(array('Y', 'N'), CAST((id + 1) % 2 + 1 AS INT)) AS fraud_ind,
  element_at(array('Y', 'N'), CAST(id % 5 % 2 + 1 AS INT)) AS vulnerable_customer,
  element_at(array('Y', 'N'), CAST(id % 7 % 2 + 1 AS INT)) AS marketing_opt_in,
  element_at(array('A', 'B', 'C', 'D'), CAST(id % 4 + 1 AS INT)) AS risk_grade,
  CAST(hash(id, 10) % 100 + 100 AS INT) AS risk_score,
  CAST(id % 12 + 1 AS INT) AS instalments,
  element_at(array('card', 'dd', 'bacs'), CAST(id % 3 + 1 AS INT)) AS pay_method,
  concat('INV', lpad(CAST(id * 11 AS STRING), 8, '0')) AS invoice_ref,
  date_add(DATE'2024-02-01', CAST(id % 600 AS INT)) AS payment_dt,
  concat('user', CAST(id AS STRING), '@example.com') AS contact_email,
  concat('07700 9', lpad(CAST(id % 100000 AS STRING), 5, '0')) AS mobile,
  concat('AB1', CAST(id % 9 AS STRING), ' ', CAST(id % 9 AS STRING), 'CD') AS post_cd,
  concat(CAST(id % 200 + 1 AS STRING), ' High Street') AS addr1,
  element_at(array('London', 'Leeds', 'Bristol', 'Glasgow'), CAST(id % 4 + 1 AS INT)) AS town,
  date_add(DATE'1950-01-01', CAST(hash(id, 11) % 9000 + 9000 AS INT)) AS date_of_birth,
  element_at(array('engineer', 'teacher', 'nurse', 'driver'), CAST(id % 4 + 1 AS INT)) AS occupation_desc,
  CAST(id % 40 + 1 AS INT) AS employees,
  round((hash(id, 12) % 900000 + 900000) * 1.0, 2) AS turnover,
  concat('SIC', lpad(CAST(id % 99 AS STRING), 5, '0')) AS sic,
  element_at(array('S1', 'S2', 'S3'), CAST(id % 3 + 1 AS INT)) AS src_system,
  concat('B', lpad(CAST(id % 50 AS STRING), 5, '0')) AS batch_no,
  TIMESTAMP'2026-11-01 00:00:00' + make_interval(0, 0, 0, 0, 0, CAST(id % 600 AS INT), 0) AS load_ts,
  date_add(DATE'2024-01-01', CAST(id % 30 AS INT)) AS upd_dt,
  sha2(CAST(id AS STRING), 256) AS row_hash,
  CAST(id % 3 AS INT) AS version_no,
  CAST(NULL AS STRING) AS spare_1,
  CAST(NULL AS STRING) AS spare_2,
  concat('free text ', CAST(id % 13 AS STRING)) AS comments,
  element_at(array('x', 'y', 'z'), CAST(id % 3 + 1 AS INT)) AS fld_a,
  CAST(id % 97 AS INT) AS fld_b,
  CAST(hash(id, 13) % 1000 AS INT) AS val3,
  element_at(array('P', 'Q'), CAST(id % 2 + 1 AS INT)) AS cd_x,
  round((hash(id, 14) % 100 + 100) / 100.0, 4) AS fx,
  CAST(id AS BIGINT) AS rec_id
FROM range(2000)
